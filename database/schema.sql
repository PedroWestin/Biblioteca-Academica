CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('LEITOR','ADMIN')),
  profile TEXT NOT NULL CHECK (profile IN ('ALUNO','PROFESSOR','ADMIN'))
);
CREATE TABLE IF NOT EXISTS books (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  title TEXT NOT NULL, author TEXT NOT NULL, category TEXT NOT NULL,
  isbn TEXT UNIQUE, year INTEGER
);
CREATE TABLE IF NOT EXISTS copies (               -- exemplares físicos
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  book_id INTEGER NOT NULL REFERENCES books(id),
  code TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'DISPONIVEL'       -- DISPONIVEL | EMPRESTADO | RESERVADO | DANIFICADO | EXTRAVIADO
);
CREATE TABLE IF NOT EXISTS loans (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  copy_id INTEGER NOT NULL REFERENCES copies(id),
  loan_type TEXT NOT NULL,                        -- ALUNO | PROFESSOR | ADMIN (produto do Factory Method)
  loaned_at TEXT NOT NULL, due_at TEXT NOT NULL, returned_at TEXT,
  renewals INTEGER NOT NULL DEFAULT 0,
  renewal_requested INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS reservations (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  book_id INTEGER NOT NULL REFERENCES books(id),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status TEXT NOT NULL DEFAULT 'PENDENTE'         -- PENDENTE | NOTIFICADA | ATENDIDA | CANCELADA
);
CREATE TABLE IF NOT EXISTS fines (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  loan_id INTEGER NOT NULL UNIQUE REFERENCES loans(id),
  amount REAL NOT NULL,
  status TEXT NOT NULL DEFAULT 'ABERTA',          -- ABERTA | PAGA
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, paid_at TEXT
);
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  message TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read INTEGER NOT NULL DEFAULT 0
);
